// Respaldo lógico de la base (equivalente a pg_dump) hecho solo con Node.js y el driver "pg".
//
// El archivo generado es SQL normal y contiene, en este orden:
//   1. borrar lo que exista (tablas, secuencias y tipos)
//   2. tipos ENUM, secuencias y tablas con sus columnas
//   3. los datos de cada tabla
//   4. claves primarias, UNIQUE, CHECK, índices y claves foráneas
// Todo va dentro de BEGIN ... COMMIT: si algo falla al restaurar, la base queda como estaba.

/** Texto entre comillas simples para SQL ('O''Brien') */
function literal(texto) {
  return `'${String(texto).replace(/'/g, "''")}'`;
}

/** Genera el SQL completo del esquema "public" de la base a la que está conectado el cliente */
export async function generarRespaldo(cliente) {
  const consultar = async (sql, parametros = []) => (await cliente.query(sql, parametros)).rows;
  const sql = [];

  const tipos = await consultar(`
    SELECT quote_ident(t.typname) AS nombre,
           string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) AS valores
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    GROUP BY t.typname
    ORDER BY t.typname`);

  const secuencias = await consultar(`
    SELECT quote_ident(c.relname) AS nombre, c.relname AS nombre_simple
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'S'
    ORDER BY c.relname`);

  const tablas = await consultar(`
    SELECT c.oid, quote_ident(c.relname) AS nombre
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
    ORDER BY c.relname`);

  // 1. Borrar lo existente
  sql.push('BEGIN;', 'SET client_min_messages = warning;', '');
  for (const tabla of tablas) sql.push(`DROP TABLE IF EXISTS public.${tabla.nombre} CASCADE;`);
  for (const secuencia of secuencias) sql.push(`DROP SEQUENCE IF EXISTS public.${secuencia.nombre} CASCADE;`);
  for (const tipo of tipos) sql.push(`DROP TYPE IF EXISTS public.${tipo.nombre} CASCADE;`);

  // 2. Estructura
  sql.push('', '-- Tipos ENUM');
  for (const tipo of tipos) sql.push(`CREATE TYPE public.${tipo.nombre} AS ENUM (${tipo.valores});`);

  sql.push('', '-- Secuencias (contadores de los id)');
  for (const secuencia of secuencias) sql.push(`CREATE SEQUENCE public.${secuencia.nombre};`);

  for (const tabla of tablas) {
    const columnas = await consultar(
      `SELECT quote_ident(a.attname) AS nombre,
              format_type(a.atttypid, a.atttypmod) AS tipo,
              a.attnotnull AS obligatorio,
              a.attidentity AS identidad,
              pg_get_expr(d.adbin, d.adrelid) AS por_defecto
       FROM pg_attribute a
       LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
       WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
       ORDER BY a.attnum`,
      [tabla.oid],
    );
    const definiciones = columnas.map((columna) => {
      let definicion = `  ${columna.nombre} ${columna.tipo}`;
      if (columna.identidad === 'a') definicion += ' GENERATED ALWAYS AS IDENTITY';
      if (columna.identidad === 'd') definicion += ' GENERATED BY DEFAULT AS IDENTITY';
      if (columna.por_defecto !== null) definicion += ` DEFAULT ${columna.por_defecto}`;
      if (columna.obligatorio) definicion += ' NOT NULL';
      return definicion;
    });
    sql.push('', `-- Tabla ${tabla.nombre}`, `CREATE TABLE public.${tabla.nombre} (`, definiciones.join(',\n'), ');');
  }

  // 3. Datos: cada tabla se guarda como un arreglo JSON y se inserta con json_populate_recordset
  sql.push('', '-- Datos');
  const resumen = {};
  for (const tabla of tablas) {
    const [fila] = await consultar(`SELECT count(*)::int AS cantidad, json_agg(t)::text AS datos FROM public.${tabla.nombre} t`);
    resumen[tabla.nombre] = fila.cantidad;
    if (fila.cantidad === 0) continue;
    sql.push(
      `INSERT INTO public.${tabla.nombre} OVERRIDING SYSTEM VALUE`,
      `SELECT * FROM json_populate_recordset(NULL::public.${tabla.nombre}, ${literal(fila.datos)});`,
    );
  }

  // Los contadores siguen donde iban (el próximo empleado no repite un id)
  sql.push('', '-- Valor actual de las secuencias');
  for (const secuencia of secuencias) {
    const [estado] = await consultar(`SELECT last_value::text AS valor, is_called AS usado FROM public.${secuencia.nombre}`);
    sql.push(`SELECT setval(${literal('public.' + secuencia.nombre)}, ${estado.valor}, ${estado.usado});`);
  }
  const duenos = await consultar(`
    SELECT quote_ident(s.relname) AS secuencia, quote_ident(t.relname) AS tabla, quote_ident(a.attname) AS columna
    FROM pg_depend d
    JOIN pg_class s ON s.oid = d.objid AND s.relkind = 'S'
    JOIN pg_class t ON t.oid = d.refobjid
    JOIN pg_namespace n ON n.oid = t.relnamespace AND n.nspname = 'public'
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
    WHERE d.deptype = 'a'`);
  for (const dueno of duenos) {
    sql.push(`ALTER SEQUENCE public.${dueno.secuencia} OWNED BY public.${dueno.tabla}.${dueno.columna};`);
  }

  // 4. Restricciones e índices (las claves foráneas al final, cuando ya existen todas las tablas)
  const restricciones = [];
  const foraneas = [];
  const indices = [];
  for (const tabla of tablas) {
    const filas = await consultar(
      `SELECT quote_ident(conname) AS nombre, contype AS tipo, pg_get_constraintdef(oid) AS definicion
       FROM pg_constraint WHERE conrelid = $1 AND contype IN ('p', 'u', 'c', 'f', 'x') ORDER BY conname`,
      [tabla.oid],
    );
    for (const fila of filas) {
      const orden = `ALTER TABLE public.${tabla.nombre} ADD CONSTRAINT ${fila.nombre} ${fila.definicion};`;
      if (fila.tipo === 'f') foraneas.push(orden);
      else restricciones.push(orden);
    }
    const filasIndices = await consultar(
      `SELECT pg_get_indexdef(i.indexrelid) AS definicion
       FROM pg_index i
       WHERE i.indrelid = $1
         AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)`,
      [tabla.oid],
    );
    for (const fila of filasIndices) indices.push(`${fila.definicion};`);
  }
  sql.push('', '-- Restricciones e índices', ...restricciones, ...indices, ...foraneas);

  sql.push('', 'COMMIT;', '');
  return { sql: sql.join('\n'), resumen };
}
